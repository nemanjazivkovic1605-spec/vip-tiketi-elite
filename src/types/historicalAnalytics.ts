  last5: { sample: number; form: string; points: number; averageFor: number | null; averageAgainst: number | null };
  last10: { sample: number; form: string; points: number; averageFor: number | null; averageAgainst: number | null };
  home: { sample: number; wins: number; draws: number; losses: number; averageFor: number | null; averageAgainst: number | null };
  away: { sample: number; wins: number; draws: number; losses: number; averageFor: number | null; averageAgainst: number | null };
